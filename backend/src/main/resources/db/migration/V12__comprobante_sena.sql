-- =====================================================================
-- Vastio · V12 · Comprobante interno de la seña (Sprint 4, mejora M-07, opcional).
-- Un comprobante por seña, con número correlativo por año (CS-AAAA-NNNNN). Volver a descargarlo da el mismo número
-- y la misma fecha de emisión. No es una factura.
-- =====================================================================

-- Último número de comprobante de cada año, como numerador_evento (V3): la fila del año queda bloqueada hasta el
-- final de la transacción, así dos emisiones simultáneas no comparten número.
CREATE TABLE numerador_comprobante (
    anio smallint NOT NULL,
    ultimo integer NOT NULL,
    CONSTRAINT pk_numerador_comprobante PRIMARY KEY (anio),
    CONSTRAINT ck_numerador_comprobante_ultimo CHECK (ultimo BETWEEN 1 AND 99999)
);

CREATE TABLE comprobante_sena (
    comprobante_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    evento_id bigint NOT NULL,
    numero varchar(14) NOT NULL,
    fecha_emision timestamptz NOT NULL DEFAULT now(),
    usuario_id bigint NOT NULL,
    CONSTRAINT pk_comprobante_sena PRIMARY KEY (comprobante_id),
    CONSTRAINT uq_comprobante_sena_evento_id UNIQUE (evento_id),
    CONSTRAINT uq_comprobante_sena_numero UNIQUE (numero),
    CONSTRAINT fk_comprobante_sena_evento_id FOREIGN KEY (evento_id) REFERENCES evento (evento_id),
    CONSTRAINT fk_comprobante_sena_usuario_id FOREIGN KEY (usuario_id) REFERENCES usuario (usuario_id)
);
