CREATE TABLE publicacion_calendar (
    evento_id bigint PRIMARY KEY REFERENCES evento(evento_id),
    calendar_id varchar(255),
    instalacion varchar(120),
    google_id varchar(64),
    estado varchar(25) NOT NULL DEFAULT 'PENDIENTE',
    pendiente varchar(15) NOT NULL DEFAULT 'EXPORTAR',
    huella varchar(64),
    huella_intento varchar(64),
    retiro_solicitado boolean NOT NULL DEFAULT false,
    etag varchar(255),
    intento timestamptz,
    exito timestamptz,
    error varchar(60),
    usuario_id bigint REFERENCES usuario(usuario_id),
    aviso_clave varchar(80),
    version integer NOT NULL DEFAULT 0,
    CONSTRAINT uq_calendar_destino UNIQUE (calendar_id, google_id),
    CONSTRAINT ck_calendar_estado CHECK (estado IN ('PENDIENTE','EXPORTADO','RETIRADO','EN_PROCESO','ERROR','INCIERTO')),
    CONSTRAINT ck_calendar_pendiente CHECK (pendiente IN ('EXPORTAR','ACTUALIZAR','RETIRAR','NINGUNA')),
    CONSTRAINT ck_calendar_identidad CHECK ((calendar_id IS NULL AND instalacion IS NULL AND google_id IS NULL)
        OR (calendar_id IS NOT NULL AND instalacion IS NOT NULL AND google_id IS NOT NULL))
);
CREATE INDEX ix_calendar_pendiente ON publicacion_calendar(pendiente) WHERE pendiente <> 'NINGUNA';
CREATE TABLE operacion_calendar (
    operacion_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id bigint NOT NULL REFERENCES evento(evento_id),
    accion varchar(30) NOT NULL,
    usuario_id bigint REFERENCES usuario(usuario_id),
    fecha_hora timestamptz NOT NULL DEFAULT now(),
    codigo varchar(60)
);
CREATE TRIGGER tg_operacion_calendar_solo_insercion BEFORE UPDATE OR DELETE ON operacion_calendar
    FOR EACH ROW EXECUTE FUNCTION fn_solo_insercion();

