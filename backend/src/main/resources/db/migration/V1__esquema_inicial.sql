    CONSTRAINT fk_proporcion_consumo_bebida_id FOREIGN KEY (bebida_id) REFERENCES bebida (bebida_id),
    CONSTRAINT uq_proporcion_consumo_1 UNIQUE (tipo_evento_id, bebida_id),
    CONSTRAINT ck_proporcion_consumo_2 CHECK (botellas_por_asistente >= 0)
);

