    CONSTRAINT ck_detalle_orden_preparacion_3 CHECK (cantidad_a_retirar >= 0)
);

-- Entrega abierta de un evento hacia una barra. Agrupa la salida inicial y los retiros adicionales.
CREATE TABLE entrega (
    entrega_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    evento_id bigint NOT NULL,
    ubicacion_destino_id smallint NOT NULL,
    orden_id bigint,
    estado varchar(10) NOT NULL,
    usuario_apertura_id bigint NOT NULL,
    fecha_apertura timestamptz NOT NULL DEFAULT now(),
    usuario_cierre_id bigint,
    fecha_cierre timestamptz,
    CONSTRAINT pk_entrega PRIMARY KEY (entrega_id),
    CONSTRAINT fk_entrega_evento_id FOREIGN KEY (evento_id) REFERENCES evento (evento_id),
    CONSTRAINT fk_entrega_ubicacion_destino_id FOREIGN KEY (ubicacion_destino_id) REFERENCES ubicacion (ubicacion_id),
    CONSTRAINT fk_entrega_orden_id FOREIGN KEY (orden_id) REFERENCES orden_preparacion (orden_id),
    CONSTRAINT fk_entrega_usuario_apertura_id FOREIGN KEY (usuario_apertura_id) REFERENCES usuario (usuario_id),
    CONSTRAINT fk_entrega_usuario_cierre_id FOREIGN KEY (usuario_cierre_id) REFERENCES usuario (usuario_id),
    CONSTRAINT ck_entrega_estado CHECK (estado IN ('ABIERTA', 'CERRADA')),
    CONSTRAINT uq_entrega_1 UNIQUE (evento_id, ubicacion_destino_id)
);

-- Asiento inalterable de mercadería (RNF-SEG-03). Solo inserción: las correcciones son nuevos asientos de ajuste.
CREATE TABLE movimiento_stock (
    movimiento_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    tipo varchar(18) NOT NULL,
    bebida_id bigint NOT NULL,
    cantidad numeric(10,2) NOT NULL,
    ubicacion_origen_id smallint,
    ubicacion_destino_id smallint,
    evento_id bigint,
    entrega_id bigint,
    ingreso_id bigint,
    movimiento_corregido_id bigint,
    motivo_id smallint,
    observacion varchar(255),
    usuario_id bigint NOT NULL,
    fecha_hora timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_movimiento_stock PRIMARY KEY (movimiento_id),
    CONSTRAINT fk_movimiento_stock_bebida_id FOREIGN KEY (bebida_id) REFERENCES bebida (bebida_id),
    CONSTRAINT fk_movimiento_stock_ubicacion_origen_id FOREIGN KEY (ubicacion_origen_id) REFERENCES ubicacion (ubicacion_id),
    CONSTRAINT fk_movimiento_stock_ubicacion_destino_id FOREIGN KEY (ubicacion_destino_id) REFERENCES ubicacion (ubicacion_id),
    CONSTRAINT fk_movimiento_stock_evento_id FOREIGN KEY (evento_id) REFERENCES evento (evento_id),
    CONSTRAINT fk_movimiento_stock_entrega_id FOREIGN KEY (entrega_id) REFERENCES entrega (entrega_id),
    CONSTRAINT fk_movimiento_stock_ingreso_id FOREIGN KEY (ingreso_id) REFERENCES ingreso (ingreso_id),
    CONSTRAINT fk_movimiento_stock_movimiento_corregido_id FOREIGN KEY (movimiento_corregido_id) REFERENCES movimiento_stock (movimiento_id),
    CONSTRAINT fk_movimiento_stock_motivo_id FOREIGN KEY (motivo_id) REFERENCES motivo (motivo_id),
    CONSTRAINT fk_movimiento_stock_usuario_id FOREIGN KEY (usuario_id) REFERENCES usuario (usuario_id),
    CONSTRAINT ck_movimiento_stock_tipo CHECK (tipo IN ('INGRESO', 'INVENTARIO_INICIAL', 'SALIDA_BARRA', 'RETIRO_ADICIONAL', 'DEVOLUCION', 'REMANENTE', 'AJUSTE', 'MERMA')),
    CONSTRAINT ck_movimiento_stock_1 CHECK (cantidad > 0),
    CONSTRAINT ck_movimiento_stock_2 CHECK (ubicacion_origen_id IS NOT NULL OR ubicacion_destino_id IS NOT NULL),
    CONSTRAINT ck_movimiento_stock_3 CHECK (tipo NOT IN ('SALIDA_BARRA','RETIRO_ADICIONAL','DEVOLUCION','REMANENTE') OR evento_id IS NOT NULL),
    CONSTRAINT ck_movimiento_stock_4 CHECK (tipo NOT IN ('AJUSTE','MERMA') OR motivo_id IS NOT NULL)
);

-- Resultado del cierre por artículo, congelado. Un cambio posterior del precio de referencia no altera el costo de eventos cerrados.
CREATE TABLE consumo_evento (
    evento_id bigint NOT NULL,
    bebida_id bigint NOT NULL,
    cantidad_entregada numeric(10,2) NOT NULL,
    cantidad_devuelta numeric(10,2) NOT NULL,
    cantidad_remanente numeric(10,2) NOT NULL,
    cantidad_consumida numeric(10,2) NOT NULL,
    precio_referencia_aplicado numeric(14,2) NOT NULL,
    costo_total numeric(14,2) NOT NULL,
    CONSTRAINT pk_consumo_evento PRIMARY KEY (evento_id, bebida_id),
    CONSTRAINT fk_consumo_evento_evento_id FOREIGN KEY (evento_id) REFERENCES evento (evento_id),
    CONSTRAINT fk_consumo_evento_bebida_id FOREIGN KEY (bebida_id) REFERENCES bebida (bebida_id)
);

-- Estimación de consumo por asistente según tipo de evento. Alimenta la orden sugerida mientras no hay histórico propio.
CREATE TABLE proporcion_consumo (
