-- Salón × fecha × turno. Se crea a demanda la primera vez que se la ocupa o bloquea. Es además el ancla de bloqueo pesimista (SELECT … FOR UPDATE) que evita que un evento y un bloqueo tomen la misma unidad en paralelo.
CREATE TABLE unidad_comercializable (
    unidad_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    salon_id smallint NOT NULL,
    fecha date NOT NULL,
    turno_id smallint NOT NULL,
    CONSTRAINT pk_unidad_comercializable PRIMARY KEY (unidad_id),
    CONSTRAINT fk_unidad_comercializable_salon_id FOREIGN KEY (salon_id) REFERENCES salon (salon_id),
    CONSTRAINT fk_unidad_comercializable_turno_id FOREIGN KEY (turno_id) REFERENCES turno (turno_id),
    CONSTRAINT uq_unidad_comercializable_1 UNIQUE (salon_id, fecha, turno_id)
);

