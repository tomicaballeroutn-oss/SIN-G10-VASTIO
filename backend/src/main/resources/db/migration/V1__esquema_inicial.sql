-- Persona que opera el sistema. La baja es lógica: se conserva el historial de lo que registró.
CREATE TABLE usuario (
    usuario_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nombre_completo varchar(120) NOT NULL,
    nombre_usuario varchar(50) NOT NULL UNIQUE,
    hash_contrasena varchar(100) NOT NULL,
    email varchar(120),
    telefono varchar(30),
    debe_cambiar_contrasena boolean NOT NULL DEFAULT true,
    activo boolean NOT NULL DEFAULT true,
    fecha_alta timestamptz NOT NULL DEFAULT now(),
    fecha_baja timestamptz,
    CONSTRAINT pk_usuario PRIMARY KEY (usuario_id)
);

-- Perfil de usuario. Los códigos son fijos porque la autorización del backend los referencia.
CREATE TABLE rol (
    rol_id smallint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo varchar(20) NOT NULL UNIQUE,
    nombre varchar(50) NOT NULL,
    CONSTRAINT pk_rol PRIMARY KEY (rol_id),
    CONSTRAINT ck_rol_codigo CHECK (codigo IN ('DIRECCION', 'COORDINACION', 'ADMINISTRACION', 'VENDEDORA', 'PLANNER', 'COMPRAS', 'BARRA', 'COCINA'))
);

-- Asignación de perfiles. Un usuario puede tener más de un perfil (p. ej. vendedora que cubre como planner).
CREATE TABLE usuario_rol (
    usuario_id bigint NOT NULL,
    rol_id smallint NOT NULL,
    fecha_asignacion timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_usuario_rol PRIMARY KEY (usuario_id, rol_id),
    CONSTRAINT fk_usuario_rol_usuario_id FOREIGN KEY (usuario_id) REFERENCES usuario (usuario_id),
    CONSTRAINT fk_usuario_rol_rol_id FOREIGN KEY (rol_id) REFERENCES rol (rol_id)
);

