-- Entidad central que vincula ambos módulos.
CREATE TABLE evento (
    evento_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    codigo varchar(14) NOT NULL UNIQUE,
    unidad_id bigint NOT NULL,
    cliente_id bigint NOT NULL,
    tipo_evento_id smallint NOT NULL,
    vendedora_id bigint NOT NULL,
    planner_id bigint,
    estado varchar(15) NOT NULL,
    nombre varchar(120) NOT NULL,
    cantidad_invitados integer,
    invitados_definitivos boolean NOT NULL,
    hora_inicio time,
    observaciones_internas text,
    importe_sena numeric(14,2),
    fecha_sena date,
    firmante_nombre varchar(120),
    firmante_dni varchar(10),
    firmante_contacto varchar(120),
    fecha_firma_contrato date,
    motivo_cancelacion_id smallint,
    detalle_cancelacion varchar(255),
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    version integer NOT NULL,
    CONSTRAINT pk_evento PRIMARY KEY (evento_id),
    CONSTRAINT fk_evento_unidad_id FOREIGN KEY (unidad_id) REFERENCES unidad_comercializable (unidad_id),
    CONSTRAINT fk_evento_cliente_id FOREIGN KEY (cliente_id) REFERENCES cliente (cliente_id),
    CONSTRAINT fk_evento_tipo_evento_id FOREIGN KEY (tipo_evento_id) REFERENCES tipo_evento (tipo_evento_id),
    CONSTRAINT fk_evento_vendedora_id FOREIGN KEY (vendedora_id) REFERENCES usuario (usuario_id),
    CONSTRAINT fk_evento_planner_id FOREIGN KEY (planner_id) REFERENCES usuario (usuario_id),
    CONSTRAINT fk_evento_motivo_cancelacion_id FOREIGN KEY (motivo_cancelacion_id) REFERENCES motivo (motivo_id),
    CONSTRAINT ck_evento_estado CHECK (estado IN ('PRE_RESERVA', 'SENADO', 'CONTRATADO', 'CONFIRMADO', 'EN_CURSO', 'REALIZADO', 'CERRADO', 'LIBERADA', 'CANCELADO')),
    CONSTRAINT ck_evento_1 CHECK (cantidad_invitados IS NULL OR cantidad_invitados >= 0),
    CONSTRAINT ck_evento_2 CHECK (importe_sena IS NULL OR importe_sena >= 0),
    CONSTRAINT ck_evento_3 CHECK (estado NOT IN ('SENADO','CONTRATADO','CONFIRMADO','EN_CURSO','REALIZADO','CERRADO') OR (importe_sena IS NOT NULL AND fecha_sena IS NOT NULL AND firmante_dni IS NOT NULL)),
    CONSTRAINT ck_evento_4 CHECK (estado NOT IN ('CONTRATADO','CONFIRMADO','EN_CURSO','REALIZADO','CERRADO') OR fecha_firma_contrato IS NOT NULL),
    CONSTRAINT ck_evento_5 CHECK (estado NOT IN ('CONFIRMADO','EN_CURSO','REALIZADO','CERRADO') OR (planner_id IS NOT NULL AND invitados_definitivos)),
    CONSTRAINT ck_evento_6 CHECK (estado <> 'CANCELADO' OR motivo_cancelacion_id IS NOT NULL)
);

