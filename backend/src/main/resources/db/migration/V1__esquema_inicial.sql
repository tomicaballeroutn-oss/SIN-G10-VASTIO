    CONSTRAINT fk_detalle_orden_preparacion_bebida_id FOREIGN KEY (bebida_id) REFERENCES bebida (bebida_id),
    CONSTRAINT uq_detalle_orden_preparacion_1 UNIQUE (orden_id, bebida_id),
