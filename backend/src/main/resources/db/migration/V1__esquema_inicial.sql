    CONSTRAINT pk_orden_preparacion PRIMARY KEY (orden_id),
    CONSTRAINT fk_orden_preparacion_evento_id FOREIGN KEY (evento_id) REFERENCES evento (evento_id),
    CONSTRAINT fk_orden_preparacion_ubicacion_origen_id FOREIGN KEY (ubicacion_origen_id) REFERENCES ubicacion (ubicacion_id),
    CONSTRAINT fk_orden_preparacion_ubicacion_destino_id FOREIGN KEY (ubicacion_destino_id) REFERENCES ubicacion (ubicacion_id),
    CONSTRAINT fk_orden_preparacion_responsable_id FOREIGN KEY (responsable_id) REFERENCES usuario (usuario_id),
    CONSTRAINT ck_orden_preparacion_estado CHECK (estado IN ('SUGERIDA', 'MODIFICADA', 'CONFIRMADA', 'DESCARTADA', 'CERRADA'))
);

-- Renglón de la orden.
CREATE TABLE detalle_orden_preparacion (
    detalle_id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
