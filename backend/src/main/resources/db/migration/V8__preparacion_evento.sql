-- B5-04: operaciones manuales independientes de las órdenes de preparación.
CREATE TABLE preparacion_evento (
    preparacion_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id bigint NOT NULL REFERENCES evento(evento_id),
    barra_id smallint NOT NULL REFERENCES ubicacion(ubicacion_id),
    origen_id smallint NOT NULL REFERENCES ubicacion(ubicacion_id),
    destino_id smallint NOT NULL REFERENCES ubicacion(ubicacion_id),
    usuario_id bigint NOT NULL REFERENCES usuario(usuario_id),
    fecha_hora timestamptz NOT NULL,
    clave varchar(100) NOT NULL,
    huella varchar(64) NOT NULL,
    CONSTRAINT uq_preparacion_clave UNIQUE(evento_id, clave),
    CONSTRAINT ck_preparacion_ubicaciones CHECK (origen_id <> destino_id)
);
CREATE INDEX ix_preparacion_evento ON preparacion_evento(evento_id, preparacion_id);
CREATE TRIGGER tg_preparacion_solo_insercion BEFORE UPDATE OR DELETE ON preparacion_evento
    FOR EACH ROW EXECUTE FUNCTION fn_solo_insercion();

ALTER TABLE movimiento_stock ADD COLUMN preparacion_id bigint REFERENCES preparacion_evento(preparacion_id);
CREATE UNIQUE INDEX ux_preparacion_bebida ON movimiento_stock(preparacion_id, bebida_id) WHERE preparacion_id IS NOT NULL;
ALTER TABLE movimiento_stock DROP CONSTRAINT ck_movimiento_stock_tipo;
ALTER TABLE movimiento_stock ADD CONSTRAINT ck_movimiento_stock_tipo CHECK (tipo IN
    ('INGRESO','INVENTARIO_INICIAL','SALIDA_BARRA','RETIRO_ADICIONAL','DEVOLUCION','REMANENTE','CONSUMO','AJUSTE','MERMA','PREPARACION'));
ALTER TABLE movimiento_stock DROP CONSTRAINT ck_movimiento_stock_3;
ALTER TABLE movimiento_stock ADD CONSTRAINT ck_movimiento_stock_3 CHECK (
    tipo NOT IN ('SALIDA_BARRA','RETIRO_ADICIONAL','DEVOLUCION','REMANENTE','CONSUMO','PREPARACION') OR evento_id IS NOT NULL);
ALTER TABLE movimiento_stock ADD CONSTRAINT ck_movimiento_preparacion CHECK (
    (tipo = 'PREPARACION' AND preparacion_id IS NOT NULL AND ubicacion_origen_id IS NOT NULL
        AND ubicacion_destino_id IS NOT NULL AND ubicacion_origen_id <> ubicacion_destino_id
        AND entrega_id IS NULL AND ingreso_id IS NULL AND cantidad = trunc(cantidad))
    OR (tipo <> 'PREPARACION' AND preparacion_id IS NULL));
